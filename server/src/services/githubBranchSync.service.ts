async function withShortClient<T>(db: PoolLike, fn: (client: PoolClientLike) => Promise<T>): Promise<T> {
  const client = await db.connect();
  try {
    return await fn(client);
  } finally {
    client.release?.();
  }
}
import crypto from 'crypto';

export interface PoolClientLike {
  query: (text: string, params?: any[]) => Promise<{ rows: any[]; rowCount?: number }>;
  release?: () => void;
}

export interface PoolLike {
  connect: () => Promise<PoolClientLike>;
}

export interface BranchSyncSummary {
  installationId: string;
  fetched: number;
  upserted: number;
  failed: number;
  errors: string[];
  truncated: boolean;
  complete: boolean;
}

interface NormalizedBranch {
  branchName: string;
  commitSha: string;
  protected: boolean;
  syncRunId?: string; // optional for updates; generated by caller
}

const SYNC_LOCK_TTL_MS = 120_000;
const SYNC_LOCK_RENEW_INTERVAL_MS = 45_000;
const PAGINATION_CAP_PAGES = 100;

/**
 * Generates a UUID for tracking a synchronization batch.
 */
function generateSyncRunId(): string {
  return crypto.randomUUID();
}

/**
 * Fetches a single page of repository branches using an installation access token.
 * Parses the response body losslessly to preserve exact branch names and commit SHAs.
 */
async function fetchBranchPage(
  token: string,
  repoOwner: string,
  repoName: string,
  page: number,
  perPage: number
): Promise<{ branches: NormalizedBranch[]; hasNext: boolean }> {
  const controller = new AbortController();
  const timeout = setTimeout(() => controller.abort(), 15_000);
  try {
    const url = `https://api.github.com/repos/${repoOwner}/${repoName}/branches?per_page=${perPage}&page=${page}`;
    const resp = await fetch(url, {
      method: 'GET',
      headers: {
        Accept: 'application/vnd.github+json',
        Authorization: `Bearer ${token}`, // installation token, never persisted/logged
        'User-Agent': 'pms-github-integration',
        'X-GitHub-Api-Version': '2022-11-28',
      },
      signal: controller.signal,
    });

    if (!resp.ok) {
      if (resp.status === 401 || resp.status === 403) {
        throw new Error('GitHub installation token was rejected while listing repository branches.');
      }
      if (resp.status === 404) {
        throw new Error('GitHub repository branches endpoint not found.');
      }
      if (resp.status === 429) {
        throw new Error('GitHub API rate limit exceeded while listing repository branches.');
      }
      throw new Error(`Failed to list GitHub repository branches (HTTP ${resp.status}).`);
    }

     const rawText = await resp.text();
     let data: any;
     try {
       data = parseJsonLossless(rawText);
     } catch {
       throw new Error('GitHub branch response was not valid JSON.');
     }

     const branches = Array.isArray(data)
       ? data
       : Array.isArray(data?.branches)
       ? data.branches
       : [];
     const totalCount = branches.length;

     const normalized: NormalizedBranch[] = [];
     for (const raw of branches) {
       const branchName = typeof raw.name === 'string' ? raw.name.trim() : null;
       const commitSha = typeof raw.commit?.sha === 'string' ? raw.commit.sha : null;
       if (!branchName || !commitSha) continue;
       normalized.push({
         branchName,
         commitSha,
         protected: raw.protected === true,
         syncRunId: undefined, // will be filled by caller
       });
     }

     const hasNext = branches.length === perPage;
     return { branches: normalized, hasNext };
  } catch (err: any) {
    if (err?.name === 'AbortError') {
      throw new Error('Timed out while listing GitHub repository branches.');
    }
    if (err instanceof Error) throw err;
    throw new Error('Failed to list GitHub repository branches.');
  } finally {
    clearTimeout(timeout);
  }
}

/**
 * Upserts branch metadata for a repository.
 * - Unique on (installation_id, repository_id, branch_name)
 * - Updates branch metadata + last_synced_at on conflict
 * - Never deletes branches missing from the sync response
 */
async function upsertBranch(
  client: PoolClientLike,
  installationId: string,
  repositoryId: string,
  branch: NormalizedBranch,
  syncRunId: string
): Promise<void> {
  await client.query(
    `INSERT INTO github_branches (
       installation_id, repository_id, branch_name, commit_sha,
       protected, last_synced_at, updated_at, sync_run_id
     ) VALUES (
       $1, $2::bigint, $3, $4,
       $5, NOW(), NOW(), $6
     )
     ON CONFLICT (installation_id, repository_id, branch_name) DO UPDATE SET
        commit_sha = EXCLUDED.commit_sha,
        protected = EXCLUDED.protected,
        last_synced_at = NOW(),
        updated_at = NOW(),
        sync_run_id = EXCLUDED.sync_run_id,
        is_deleted = FALSE`,
    [
      installationId,
      repositoryId,
      branch.branchName,
      branch.commitSha,
      branch.protected,
      syncRunId,
    ]
  );
}

/**
 * Mark existing branches as deleted (soft delete) for a given repository.
 * Only updates branches that were not updated in the current sync_run.
 * Atomically verifies the installation lock is still owned by this sync operation.
 */
async function markDeletedBranches(
  client: PoolClientLike,
  installationId: string,
  repositoryId: string,
  currentSyncRunId: string,
  lockToken: string,
  ownerId: string
): Promise<void> {
  const { rowCount: _rowCount } = await client.query(
    `UPDATE github_branches
        SET is_deleted = TRUE,
            updated_at = NOW()
      WHERE installation_id = $1
        AND repository_id = $2
        AND sync_run_id IS DISTINCT FROM $3
        AND is_deleted = FALSE
        AND EXISTS (
          SELECT 1 FROM github_installation_locks
          WHERE installation_id = $1
            AND lock_token = $4
            AND owner_id = $5
            AND expires_at > NOW()
        )`,
    [installationId, repositoryId, currentSyncRunId, lockToken, ownerId]
  );
  // If _rowCount is 0, lock ownership was lost; do not mark branches deleted.
}



/**
 * Synchronizes branch metadata for a GitHub installation.
 *
 * - Requires an active installation record (checked by caller/route).
 * - Acquires installation lock with exact installation ID/owner/token ownership.
 * - Renews lock with exact ownership checks (DB time) while network sync runs.
 * - Stops safely on renewal/ownership loss; never takes over another worker's lock.
 * - Releases lock in finally.
 * - Generates a short‑lived installation access token (never persisted).
 * - Paginates through all repositories under the installation.
 * - Upserts branch metadata; marks absent branches as deleted after successful repo sync.
 * - Reports truncation explicitly when pagination safety cap is reached.
 */
export async function syncInstallationBranches(
  db: PoolLike,
  installationId: InstallationIdLike
): Promise<BranchSyncSummary> {
  const instId = normalizeInstallationId(installationId);
  const summary: BranchSyncSummary = {
    installationId: instId,
    fetched: 0,
    upserted: 0,
    failed: 0,
    errors: [],
    truncated: false,
    complete: true,
  };

  // Step 1: Acquire lock and capture client
  let _dbClient: PoolClientLike;
  const lock = await withShortClient(db, (client) => {
    _dbClient = client as PoolClientLike;
    return acquireInstallationLock(client, {
      installationId: instId,
      ownerId: `branch-sync:${instId}`,
      ttlMs: SYNC_LOCK_TTL_MS,
    })
  });

  if (!lock) {
    throw new Error('Branch synchronization is already in progress for this installation.');
  }

  const lockToken = lock.lockToken;
  const lockOwnerId = lock.ownerId;

  let ownershipLost = false;
  let renewalTimer: ReturnType<typeof setInterval> | null = null;
  let renewalInFlight = false;

  const stopForOwnershipLoss = (message: string) => {
    if (ownershipLost) return;
    ownershipLost = true;
    summary.truncated = true;
    summary.complete = false;
    if (summary.errors.length < 20 && !summary.errors.includes(message)) {
      summary.errors.push(message);
    }
  };

  const startRenewal = (currentLock: InstallationLock) => {
    renewalTimer = setInterval(() => {
      if (renewalInFlight || ownershipLost) return;
      renewalInFlight = true;
      void withShortClient(db, (client) => renewInstallationLock(client, currentLock, SYNC_LOCK_TTL_MS))
        .then((renewed) => {
          if (!renewed) {
            stopForOwnershipLoss('Branch synchronization stopped because installation lock ownership was lost.');
          }
        })
        .catch(() => {
          stopForOwnershipLoss('Branch synchronization stopped because installation lock renewal failed.');
        })
        .finally(() => {
          renewalInFlight = false;
        });
    }, SYNC_LOCK_RENEW_INTERVAL_MS);
    (renewalTimer as any)?.unref?.();
  };

  try {
    startRenewal(lock);

    // Token with both metadata and contents read for branch listing
    const { token } = await generateInstallationAccessToken(instId, true);

    if (ownershipLost) return summary;

     // Get list of repositories for this installation (using existing repo sync logic)
     const repos = await withShortClient(db, async (c) => {
       const reposRes = await c.query(
         `SELECT github_repo_id, full_name FROM github_repositories WHERE installation_id = $1`,
         [instId]
       );
       return reposRes.rows;
     });

    // Track repositories that completed successfully for deletion marking, with their sync run ID
    const successfulRepos = new Map<string, string>();

    // For each repository, fetch branches and upsert
    for (const repo of repos) {
      if (ownershipLost) break;

      // Extract owner and repo name from full_name
      const [repoOwner, repoName] = repo.full_name.split('/');
      if (!repoOwner || !repoName) {
        summary.failed++;
        if (summary.errors.length < 20) {
          summary.errors.push(`repo ${repo.full_name}: invalid full_name format`);
        }
        continue;
      }

      const perPage = 100;
      let page = 1;
      let hasNext = true;
      const syncRunId = generateSyncRunId();

      let repoSuccessful = false;

      while (hasNext) {
        if (ownershipLost) break;
        if (page > PAGINATION_CAP_PAGES) {
          summary.truncated = true;
          summary.complete = false;
          if (summary.errors.length < 20 && !summary.errors.includes('Pagination limit reached; branch sync truncated.')) {
            summary.errors.push('Pagination limit reached; branch sync truncated.');
          }
          break;
        }

        try {
          const { branches, hasNext: next } = await fetchBranchPage(token, repoOwner, repoName, page, perPage);
          summary.fetched += branches.length;

          for (const branch of branches) {
            if (ownershipLost) break;
            branch.syncRunId = syncRunId;
             try {
               await withShortClient(db, (c) => upsertBranch(c, instId, repo.github_repo_id, branch, syncRunId));
               summary.upserted++;
             } catch (err: any) {
              summary.failed++;
              if (summary.errors.length < 20) {
                summary.errors.push(`repo ${repo.full_name}, branch ${branch.branchName}: ${typeof err?.message === 'string' ? err.message : 'upsert failed'}`);
              }
            }
          }

          hasNext = next;
          page++;
          repoSuccessful = true;
        } catch (err: any) {
          summary.failed++;
          if (summary.errors.length < 20) {
            summary.errors.push(`repo ${repo.full_name}: ${typeof err?.message === 'string' ? err.message : 'branch fetch failed'}`);
          }
          break;
        }
      }

      if (repoSuccessful) {
        successfulRepos.set(repo.github_repo_id, syncRunId);
      }
    }

    // After successfully processing all repositories, mark absent branches as deleted
    if (!ownershipLost) {
      for (const repo of repos) {
        if (ownershipLost) break;
        // Only mark branches as deleted for repositories that completed successfully
         if (successfulRepos.has(repo.github_repo_id)) {
           const repoSyncRunId = successfulRepos.get(repo.github_repo_id);
           if (repoSyncRunId) {
             await withShortClient(db, (c) => markDeletedBranches(c, instId, repo.github_repo_id, repoSyncRunId, lockToken, lockOwnerId));
           }
         }
      }
    }

    return summary;
  } finally {
    if (renewalTimer) clearInterval(renewalTimer);
    // Final renewal attempt is not performed after work stops; release only exact owner/token.
    await withShortClient(db, (client) => releaseInstallationLock(client, lock)).catch(() => {});
  }
}

/**
 * Lists stored branch metadata for an installation (no GitHub API call).
 */
export async function listInstallationBranches(
  client: PoolClientLike,
  installationId: InstallationIdLike
): Promise<any[]> {
  const instId = normalizeInstallationId(installationId);
  const res = await client.query(
    `SELECT
       id,
       installation_id::text AS installation_id,
       repository_id::text AS repository_id,
       branch_name,
       commit_sha,
       protected,
       last_synced_at,
       updated_at,
       is_deleted,
       sync_run_id
     FROM github_branches
     WHERE installation_id = $1
     ORDER BY repository_id ASC, branch_name ASC`,
    [instId]
  );
  return res.rows;
}
